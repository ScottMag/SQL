WITH DATEPARAMS AS
(SELECT CAST('2014-04-01' AS DATE) AS MONTHSTART,
        EOMONTH(CAST('2014-04-01' AS DATE)) AS MONTHEND),
ACTUALREVENUE AS
(SELECT SUM(SOH.SUBTOTAL) AS ACTUALREVENUE,
        DAY(DP.MONTHEND) AS DAYSINMONTH
 FROM DATEPARAMS AS DP
 INNER JOIN SALES.SALESORDERHEADER AS SOH
 ON SOH.ORDERDATE >= DP.MONTHSTART
 AND SOH.ORDERDATE <= DP.MONTHEND
 GROUP BY DP.MONTHEND)

SELECT ROUND(ACTUALREVENUE / DAYSINMONTH, 2) AS ACTUALPERDAY,
       ROUND(ACTUALREVENUE, 2) AS ACTUALREVENUE
FROM ACTUALREVENUE;
